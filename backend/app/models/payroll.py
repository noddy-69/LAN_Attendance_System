import uuid

from sqlalchemy import ForeignKey, Integer, Text, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base


class SalaryDeduction(Base):
    """Monthly late-penalty deduction record.

    All monetary values in INTEGER paise (1 rupee = 100 paise).
    Generated by the Celery payroll task on the 1st of each month.
    """

    __tablename__ = "salary_deductions"
    __table_args__ = (
        UniqueConstraint(
            "employee_id", "month", "year",
            name="uq_salary_deduction_employee_month_year",
        ),
    )

    employee_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("employees.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    month: Mapped[int] = mapped_column(Integer, nullable=False)   # 1–12
    year: Mapped[int] = mapped_column(Integer, nullable=False)

    late_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )

    # ── New percentage-of-a-day model ────────────────────────────────────
    # Snapshot of the employee's monthly salary used for this deduction (paise).
    monthly_salary_paise: Mapped[int | None] = mapped_column(Integer, nullable=True)
    # daily_salary = monthly_salary / salary_days_per_month (paise).
    daily_salary_paise: Mapped[int | None] = mapped_column(Integer, nullable=True)
    # penalty units = late_count // late_days_per_unit (e.g. one per 3 lates).
    penalty_units: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )
    # Net penalty in "centidays" after grace (×100; 50 = 0.5 day, 150 = 1.5 days).
    net_penalty_days_x100: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )

    # = round(daily_salary_paise × net_penalty_days_x100 / 100)
    total_deduction_paise: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )

    # ── Legacy per-late columns (historical rows only; new model leaves NULL) ──
    allowed_late_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    excess_late_count: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default="0"
    )
    penalty_per_late_paise: Mapped[int | None] = mapped_column(Integer, nullable=True)

    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    employee: Mapped["Employee"] = relationship(
        "Employee", back_populates="salary_deductions"
    )
